using System.Text;

namespace PaceWheel.Cli.Commands;

/// <summary>
/// Regenerates the block between the markers in docs/device-notes.md with fresh output of
/// list, di-info and descriptor. Hand-written text outside the markers is kept.
/// </summary>
internal static class NotesCommand
{
    private const string BeginMarker = "<!-- BEGIN GENERATED: pacewheel notes -->";
    private const string EndMarker = "<!-- END GENERATED: pacewheel notes -->";

    public static int Run(string[] args)
    {
        int pathIndex = Array.IndexOf(args, "--path");
        string path = pathIndex >= 0 && pathIndex + 1 < args.Length
            ? Path.GetFullPath(args[pathIndex + 1])
            : Path.Combine(FindRepositoryRoot(), "docs", "device-notes.md");

        var block = new StringBuilder();
        block.AppendLine(BeginMarker);
        block.AppendLine($"_Generated by `pacewheel notes` on {DateTime.Now:yyyy-MM-dd HH:mm}. Rerun the command instead of editing this block._");
        block.AppendLine();
        AppendSection(block, "pacewheel list", w => HidCommands.List(w));
        AppendSection(block, "pacewheel di-info", w => DirectInputCommands.Info(w));
        AppendSection(block, "pacewheel descriptor", w => HidCommands.Descriptor(w, hexOnly: false), collapsed: true);
        block.Append(EndMarker);

        string content;
        if (File.Exists(path))
        {
            string existing = File.ReadAllText(path);
            int begin = existing.IndexOf(BeginMarker, StringComparison.Ordinal);
            int end = existing.IndexOf(EndMarker, StringComparison.Ordinal);
            content = begin >= 0 && end > begin
                ? existing[..begin] + block + existing[(end + EndMarker.Length)..]
                : existing.TrimEnd() + Environment.NewLine + Environment.NewLine + "## Raw diagnostic output" + Environment.NewLine + Environment.NewLine + block + Environment.NewLine;
        }
        else
        {
            content = $"""
                # Device notes: Rampage Pace V987 (USB 11FF:2370)

                ## Raw diagnostic output

                {block}

                """;
        }

        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, content.ReplaceLineEndings(Environment.NewLine));
        Console.WriteLine($"Updated {path}");
        return 0;
    }

    private static void AppendSection(StringBuilder block, string title, Func<TextWriter, int> command, bool collapsed = false)
    {
        using var writer = new StringWriter();
        int exitCode = command(writer);
        string text = writer.ToString().TrimEnd();

        block.AppendLine($"### `{title}`");
        block.AppendLine();
        if (exitCode != 0)
        {
            block.AppendLine($"_Command exited with code {exitCode}._");
            block.AppendLine();
        }
        if (collapsed)
        {
            int lineCount = text.Split('\n').Length;
            block.AppendLine($"<details><summary>Full output ({lineCount} lines)</summary>");
            block.AppendLine();
        }
        block.AppendLine("```text");
        block.AppendLine(text);
        block.AppendLine("```");
        if (collapsed)
        {
            block.AppendLine();
            block.AppendLine("</details>");
        }
        block.AppendLine();
    }

    private static string FindRepositoryRoot()
    {
        for (var dir = new DirectoryInfo(Environment.CurrentDirectory); dir is not null; dir = dir.Parent)
        {
            if (File.Exists(Path.Combine(dir.FullName, "pace-wheel-control.sln")))
            {
                return dir.FullName;
            }
        }
        return Environment.CurrentDirectory;
    }
}
