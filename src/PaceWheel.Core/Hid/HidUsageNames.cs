namespace PaceWheel.Core.Hid;

/// <summary>Names for the usage pages and usages that matter for wheels (HID Usage Tables 1.x, PID 1.0).</summary>
public static class HidUsageNames
{
    public const ushort GenericDesktop = 0x01;
    public const ushort Simulation = 0x02;
    public const ushort Keyboard = 0x07;
    public const ushort Led = 0x08;
    public const ushort Button = 0x09;
    public const ushort Ordinal = 0x0A;
    public const ushort Consumer = 0x0C;
    public const ushort Pid = 0x0F;

    public static string Page(ushort page) => page switch
    {
        GenericDesktop => "Generic Desktop",
        Simulation => "Simulation Controls",
        0x03 => "VR Controls",
        0x04 => "Sport Controls",
        0x05 => "Game Controls",
        0x06 => "Generic Device Controls",
        Keyboard => "Keyboard/Keypad",
        Led => "LED",
        Button => "Button",
        Ordinal => "Ordinal",
        0x0B => "Telephony",
        Consumer => "Consumer",
        0x0D => "Digitizer",
        0x0E => "Haptics",
        Pid => "Physical Interface Device (PID)",
        0x10 => "Unicode",
        >= 0xFF00 => $"Vendor Defined 0x{page:X4}",
        _ => $"Page 0x{page:X2}",
    };

    public static string Usage(ushort page, ushort usage)
    {
        string? name = page switch
        {
            GenericDesktop => GenericDesktopUsage(usage),
            Simulation => SimulationUsage(usage),
            Button => usage == 0 ? "No Button" : $"Button {usage}",
            Ordinal => $"Instance {usage}",
            Keyboard => $"Key 0x{usage:X2}",
            Led => $"LED 0x{usage:X2}",
            Consumer => usage == 0x01 ? "Consumer Control" : null,
            Pid => PidUsage(usage),
            _ => null,
        };
        return name ?? $"0x{usage:X2}";
    }

